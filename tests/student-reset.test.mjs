import test from 'node:test';
import assert from 'node:assert/strict';
import { DatabaseSync } from 'node:sqlite';
import { mkdtempSync, rmSync, existsSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { resetStudentsOnce } from '../lib/student-reset.mjs';

test('explicit cleanup backs up WAL data, removes all student snapshots, preserves accounts/rules, and does not clear new students twice', t => {
  const dir = mkdtempSync(join(tmpdir(), 'sgu-reset-'));
  const db = new DatabaseSync(join(dir, 'sgu.db'));
  t.after(() => { db.close(); rmSync(dir, { recursive: true, force: true }); });
  db.exec(`PRAGMA journal_mode=WAL;
    CREATE TABLE meta(key TEXT PRIMARY KEY,value TEXT NOT NULL);
    CREATE TABLE students(id TEXT PRIMARY KEY,data TEXT);
    CREATE TABLE matches(id TEXT PRIMARY KEY,data TEXT);
    CREATE TABLE users(id TEXT PRIMARY KEY,password TEXT);
    CREATE TABLE programs(id TEXT PRIMARY KEY,data TEXT);
    CREATE TABLE events(id TEXT PRIMARY KEY,kind TEXT,subject TEXT,actor TEXT,detail TEXT,created_at TEXT);
    INSERT INTO students VALUES('sample','demo'),('actual','user-created');
    INSERT INTO matches VALUES('snapshot','student-private-data');
    INSERT INTO users VALUES('admin','password-hash');
    INSERT INTO programs VALUES('GLA','edited-rule');
    INSERT INTO events VALUES('s','student','name','admin','old-student-data','now'),('m','match','name','admin','old-snapshot','now'),('p','rule','GLA','admin','rule-change','now');`);
  const result = resetStudentsOnce(db, dir);
  assert.equal(result.students, 2); assert.equal(result.matches, 1); assert.equal(result.skipped, false);
  assert.ok(existsSync(result.backupPath));
  const backup = new DatabaseSync(result.backupPath, { readOnly: true });
  assert.equal(backup.prepare('SELECT count(*) AS n FROM students').get().n, 2);
  assert.equal(backup.prepare('SELECT count(*) AS n FROM matches').get().n, 1);
  backup.close();
  assert.equal(db.prepare('SELECT count(*) AS n FROM students').get().n, 0);
  assert.equal(db.prepare('SELECT count(*) AS n FROM matches').get().n, 0);
  assert.equal(db.prepare("SELECT count(*) AS n FROM events WHERE kind IN ('student','match')").get().n, 0);
  assert.equal(db.prepare('SELECT password FROM users').get().password, 'password-hash');
  assert.equal(db.prepare('SELECT data FROM programs').get().data, 'edited-rule');
  assert.equal(db.prepare("SELECT count(*) AS n FROM events WHERE kind='rule'").get().n, 1);
  db.exec("INSERT INTO students VALUES('new-student','new record');");
  assert.equal(resetStudentsOnce(db, dir).skipped, true);
  assert.equal(db.prepare('SELECT count(*) AS n FROM students').get().n, 1);
});
